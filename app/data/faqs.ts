export function faqsByType(...types: number[]): FaqItem[] {
  return faqs.filter((item) => types.includes(item.type));
}

export function faqCategoriesByType(...types: number[]): FaqCategory[] {
  const typeSet = new Set(types);
  return types
    .map((type) => faqCategories.find((category) => category.id === type))
    .filter((category): category is FaqCategory =>
      Boolean(category && typeSet.has(category.id)),
    );
}
